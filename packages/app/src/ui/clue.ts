/**
 * 线索 —— 正文里的一个数字，其实是一扇门。
 *
 * ## 它解决的那一个问题
 *
 * 侧室（`/parts`、`/roster`、`/marks`、`/lag`）**不进目录**（docs/23 §S9）。
 * 它们不是这个站的第八、第九个面，它们是已经在说的那几句话被说到底的样子。
 * 但不进目录的房间必须还是到得了 —— 否则它就不是"侧室"，是"没上线"。
 *
 * 所以门开在正文里：`/about` 说「物种 28」的时候，那个 **28** 就是二十八个物种
 * 摆在一起的那一张图；说「部件 208」的时候，那个 **208** 就是那 208 件本身。
 * 一个可以被穷举的数，通向它的穷举 —— 这是这个站唯一的一条**线索**规则，
 * 没有任何一处写着"这里有门"。
 *
 * （2026-09-14 起还有第二种门：**旁注**，`ui/asides.ts`。它把正文里一个短语链到
 * 目录外的一台仪器，静止态就是普通链接的样子，因为它不假装是暗门。
 * 两种门各守各的规矩，不要合并 —— 见 docs/23 §S9.2。）
 *
 * ## 四条约束，每一条都是一次否决
 *
 * 1. **静止态和周围的字一模一样。** 没有下划线、没有换色、没有小箭头、
 *    没有虚线、没有 `cursor: help`。`.ed a` 那条常驻的 1px 底线在这里被摘掉了
 *    （见 `clue.css`）—— 留着它，这就不是线索，是一条排版不一致的链接。
 *
 * 2. **一个都没被发现，这一页仍然是完整的。** 所以门只开在**本来就存在**的
 *    数字上，不为了开门往正文里加一个词。删掉这个文件，`/about` 少的是四扇门，
 *    不是四段话。这条是可验证的：`clue()` 只接受调用方已经建好的节点。
 *
 * 3. **摸到了就得有反应，而且是这个站已有的那一种。** hover 和
 *    `:focus-visible` 都把 `.ed a` 的那条强调色底线从左边长出来 ——
 *    和这一页上每一条普通链接**逐帧相同**。发现一扇门的回报是
 *    "哦，它是个链接"，不是一套只在这里出现的新语汇。
 *
 * 4. **读屏不许被瞒着。** 一扇对辅助技术不可见的暗门不叫含蓄，叫坏了。
 *    所以每一扇门都带一段视觉上不可见、但读屏会念出来的目的地
 *    （`sb-clue__where`）：屏幕上是「208」，读屏念的是
 *    「208 侧室：部件档案 链接」。
 *    这确实让读屏用户比看得见的人更早知道门在哪 —— 两害相权，
 *    "有人更早知道"远比"有一类人永远进不去"轻。键盘同理：它就是一个
 *    真的 `<a href>`，tab 得到，回车进得去，不需要任何额外代码。
 */
import { setBi, type BiText } from './i18n.ts';
import './clue.css';

export interface ClueOptions {
  /** 门通向哪里。站内绝对路径，`cleanUrls` 已经把 `.html` 去掉了 */
  href: string;
  /**
   * 门后面是什么。**只给读屏念**，屏幕上不占一个像素。
   * 走 `BiText` 而不是一条 `aria-label` 字符串：中英并置是这个站的
   * 设计决定（`ui/i18n.ts` 的文件头），而属性里拼不出并置的排版。
   */
  where: BiText;
}

/**
 * 把已经建好的节点变成一扇门。
 *
 * **只接受节点，不接受文本。** 这一条是第 2 条约束的实现：
 * 调用方必须先把那个数字按它本来的样子建出来（`num()` / `ord()` / …），
 * 才有东西可以交给这里 —— 于是"为了开门而往正文里加字"这件事做不到。
 */
export function clue(options: ClueOptions, ...kids: Node[]): HTMLAnchorElement {
  const a = document.createElement('a');
  a.className = 'sb-clue';
  a.href = options.href;

  const where = document.createElement('span');
  where.className = 'sb-clue__where';
  setBi(where, options.where);

  a.append(...kids, where);
  return a;
}
